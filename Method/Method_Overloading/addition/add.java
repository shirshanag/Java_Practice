public class Main{
    static int intadd(int a, int b){
        return a+b;
    }
    static double doubleadd(double a, double b){
        return a+b;
    }
    public static void main(String[] args){
        System.out.println("Double addition:"+doubleadd(2.3,4.5));
        System.out.println("Integer addition:"+intadd(2,4));
    }
}
